#!/usr/bin/env bash
# Behaviour of the installed first-boot runner and secrets library
# (ADR-0001 §Decision: secrets are generated on first boot). Runs
# /usr/local/sbin/safbox-firstboot on the target against a throwaway
# directory tree, never against /etc/safbox, and checks that it:
#   - creates its etc directory root-owned 0700
#   - runs executable hooks in lexical order and skips non-executables
#   - records completion and is a no-op on the next run
#   - writes no marker when a hook fails, and retries on the next run
#   - keeps a secret it already generated (safbox_ensure_secret)
# Requires the playbook to have been applied, and:
#   SAFBOX_HOST, SAFBOX_USER (passwordless sudo), SAFBOX_KEY
set -euo pipefail

if [[ -z "${SAFBOX_HOST:-}" || -z "${SAFBOX_USER:-}" || -z "${SAFBOX_KEY:-}" ]]; then
  echo "SKIP: set SAFBOX_HOST, SAFBOX_USER and SAFBOX_KEY to a host the playbook was applied to" >&2
  exit 2
fi
[[ -r "$SAFBOX_KEY" ]] || { echo "FAIL: SAFBOX_KEY=$SAFBOX_KEY is not readable" >&2; exit 2; }

ssh -o BatchMode=yes -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null -o LogLevel=ERROR \
  -i "$SAFBOX_KEY" "${SAFBOX_USER}@${SAFBOX_HOST}" 'sudo -n bash -s' <<'REMOTE'
set -euo pipefail
RUNNER=/usr/local/sbin/safbox-firstboot
fails=0
pass() { printf 'ok   - %s\n' "$*"; }
fail() { printf 'FAIL - %s\n' "$*"; fails=$((fails + 1)); }
check() { local desc=$1; shift; if "$@"; then pass "$desc"; else fail "$desc"; fi; }

# Under /root: a hardened /tmp may be mounted noexec.
sandbox=$(mktemp -d /root/safbox-firstboot-test.XXXXXX)
trap 'rm -rf "$sandbox"' EXIT

run() {  # run DIR: invoke the runner with every path inside DIR
  env -i PATH=/usr/sbin:/usr/bin \
    SAFBOX_ETC_DIR="$1/etc" SAFBOX_STATE_DIR="$1/state" SAFBOX_LIB_DIR=/usr/local/lib/safbox \
    "$RUNNER"
}
hook() {  # hook DIR NAME BODY [MODE]
  mkdir -p "$1/etc/firstboot.d"
  printf '#!/usr/bin/env bash\nset -euo pipefail\n%s\n' "$3" > "$1/etc/firstboot.d/$2"
  chmod "${4:-0755}" "$1/etc/firstboot.d/$2"
}

# 1. Creates its etc directory, root-owned 0700, when it does not exist.
d=$sandbox/create
mkdir -p "$d"
check "first run with no etc directory succeeds" run "$d"
check "etc directory created with mode 700 and owner root" \
  test "$(stat -c '%a %U %G' "$d/etc")" = "700 root root"
check "completion marker written" test -s "$d/state/firstboot.done"

# 2. Order, skipping, marker, no second run.
d=$sandbox/order
hook "$d" 20-second 'echo second >> "$SAFBOX_STATE_DIR/order"'
hook "$d" 05-first 'mkdir -p "$SAFBOX_STATE_DIR"; echo first >> "$SAFBOX_STATE_DIR/order"'
hook "$d" 10-skipped 'echo skipped >> "$SAFBOX_STATE_DIR/order"' 0644
hook "$d" 30-secret 'source "$SAFBOX_LIB_DIR/secrets.sh"; safbox_ensure_secret "$SAFBOX_ETC_DIR/test.env" TOKEN'
check "run with hooks succeeds" run "$d"
check "executable hooks ran in lexical order; non-executable skipped" \
  test "$(paste -sd, "$d/state/order")" = "first,second"
check "marker records a UTC timestamp" grep -qE '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}Z$' "$d/state/firstboot.done"
check "env file written root-only 0600" test "$(stat -c '%a %U' "$d/etc/test.env")" = "600 root"
check "secret is 64 hex characters" grep -qE '^TOKEN=[0-9a-f]{64}$' "$d/etc/test.env"
out=$(run "$d")
check "second run reports completion and does nothing" grep -q 'already completed' <<<"$out"
check "no hook ran on the second run" test "$(paste -sd, "$d/state/order")" = "first,second"

# 3. A failing hook leaves no marker; the next run retries and keeps secrets.
d=$sandbox/retry
hook "$d" 10-secret 'source "$SAFBOX_LIB_DIR/secrets.sh"; safbox_ensure_secret "$SAFBOX_ETC_DIR/test.env" TOKEN'
hook "$d" 20-flaky 'test -e "$SAFBOX_STATE_DIR/ready"'
if run "$d" >/dev/null 2>&1; then fail "run with a failing hook exits non-zero"; else pass "run with a failing hook exits non-zero"; fi
check "no marker after a failed hook" test ! -e "$d/state/firstboot.done"
first_secret=$(cat "$d/etc/test.env")
touch "$d/state/ready"
check "retry after the failure succeeds" run "$d"
check "marker written after the retry" test -s "$d/state/firstboot.done"
check "secret generated by the failed run is kept" test "$(cat "$d/etc/test.env")" = "$first_secret"

# 4. The library rejects bad input.
# shellcheck source=/dev/null
source /usr/local/lib/safbox/secrets.sh
if safbox_ensure_secret "$sandbox/x.env" 'bad-key' 2>/dev/null; then fail "invalid key rejected"; else pass "invalid key rejected"; fi
if safbox_ensure_secret "$sandbox/x.env" KEY 8 2>/dev/null; then fail "fewer than 16 bytes rejected"; else pass "fewer than 16 bytes rejected"; fi

if (( fails > 0 )); then echo "FAIL: ${fails} check(s) failed"; exit 1; fi
echo "PASS: first-boot runner behaviour"
REMOTE
