#!/usr/bin/env bash
# Generate verify/safbox-rhel10-stig-overlay/baseline-titles.yml: the ID,
# severity and title of every control of the MITRE RHEL 10 STIG baseline at
# the commit the overlay pins. scripts/deviations-doc.sh reads it to name the
# remaining failing controls in docs/deviations.md without fetching the
# baseline, so the deviations check stays offline. Never edit the file by
# hand: run this after changing the overlay's pinned ref.
# tests/verify/overlay.sh regenerates it against the fetched baseline and
# fails if the committed file differs; scripts/deviations-check.sh fails if
# its recorded ref is not the overlay's.
#
#   scripts/baseline-titles.sh [output]
#   (default: verify/safbox-rhel10-stig-overlay/baseline-titles.yml)
#
# Needs CINC Auditor and network access to fetch the pinned baseline.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OVERLAY=$ROOT/verify/safbox-rhel10-stig-overlay
OUT=${1:-$OVERLAY/baseline-titles.yml}
for tool in cinc-auditor ansible-playbook; do
  command -v "$tool" >/dev/null || { echo "baseline-titles.sh: $tool not found" >&2; exit 1; }
done
read -r -a PY <<<"$(head -1 "$(command -v ansible-playbook)" | sed 's/^#!//')"

# Vendor a scratch copy so the tree gains no lock file or vendor/, then let
# CINC Auditor parse the controls (titles are Ruby literals of several
# forms, so they are not read with a regular expression).
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cp -R "$OVERLAY" "$work/overlay"
cinc-auditor vendor "$work/overlay" --chef-license accept-silent >/dev/null 2>&1 \
  || { echo "baseline-titles.sh: cannot fetch the overlay's pinned baseline" >&2; exit 1; }
# The overlay's own JSON carries no titles for included controls; read the
# vendored baseline itself.
baseline=$(grep -l '^name: redhat-enterprise-linux-10-stig-baseline$' "$work"/overlay/vendor/*/inspec.yml | head -1)
[ -n "$baseline" ] || { echo "baseline-titles.sh: the vendored baseline was not found" >&2; exit 1; }
cinc-auditor json "$(dirname "$baseline")" --chef-license accept-silent 2>/dev/null >"$work/profile.json" \
  || { echo "baseline-titles.sh: cinc-auditor json failed" >&2; exit 1; }

"${PY[@]}" - "$OVERLAY/inspec.yml" "$work/profile.json" "$OUT" <<'PY'
import json, pathlib, sys, yaml
meta, profile, out = (pathlib.Path(a) for a in sys.argv[1:4])
BASE = "redhat-enterprise-linux-10-stig-baseline"
ref = next(d["ref"] for d in yaml.safe_load(meta.read_text())["depends"] if d["name"] == BASE)
controls = {}
for c in json.loads(profile.read_text())["controls"]:
    if c["id"].startswith("SV-") and c.get("title"):
        controls[c["id"]] = {"severity": (c.get("tags") or {}).get("severity", ""),
                             "title": " ".join(c["title"].split())}
if len(controls) < 100:
    sys.exit(f"baseline-titles.sh: only {len(controls)} baseline controls found")


class Dumper(yaml.SafeDumper):
    """Indents lists under their key, as yamllint (ansible/.yamllint) expects."""
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


header = ("---\n"
          "# Generated by scripts/baseline-titles.sh from the MITRE RHEL 10 STIG\n"
          "# baseline at the overlay's pinned ref. Do not edit; regenerate.\n")
body = yaml.dump({"baseline_ref": ref, "controls": dict(sorted(controls.items()))},
                 Dumper=Dumper, sort_keys=False, default_flow_style=False, width=100, allow_unicode=True)
out.write_text(header + body)
print(f"baseline-titles.sh: {len(controls)} controls at {ref} -> {out}")
PY
