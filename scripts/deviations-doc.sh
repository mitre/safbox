#!/usr/bin/env bash
# Generate docs/deviations.md (ADR-0001 Phase 7) from the hardening role's
# deviations.yml and not_applied.yml, the overlay's known-defects.yml and
# baseline-titles.yml, and the failing STIG lists locked in
# verify/thresholds/. The guide is never edited by hand: change a source and
# run this (after relocking a threshold too). scripts/deviations-check.sh
# fails while the committed guide differs from what this writes. Offline.
#
#   scripts/deviations-doc.sh [output]   (default: docs/deviations.md)
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=${1:-$ROOT/docs/deviations.md}
command -v ansible-playbook >/dev/null || { echo "deviations-doc.sh: ansible-playbook not installed" >&2; exit 1; }
read -r -a PY <<<"$(head -1 "$(command -v ansible-playbook)" | sed 's/^#!//')"

"${PY[@]}" - "$ROOT" "$OUT" <<'PY'
import pathlib, sys, yaml
root, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
role = root / "ansible/roles/hardening/vars"
deviations = yaml.safe_load((role / "deviations.yml").read_text())["hardening_deviations"] or []
not_applied = yaml.safe_load((role / "not_applied.yml").read_text())["hardening_not_applied"] or []
known = yaml.safe_load((root / "verify/safbox-rhel10-stig-overlay/known-defects.yml").read_text())["known_defects"] or []
titles = yaml.safe_load((root / "verify/safbox-rhel10-stig-overlay/baseline-titles.yml").read_text())["controls"]
SEVERITIES = ("high", "medium", "low")
# Failing controls nobody has looked at yet are triaged on this card.
TRIAGE_CARD = "safbox-m5f.37"


def failing(context):
    t = yaml.safe_load((root / f"verify/thresholds/{context}.yml").read_text())
    # STIG controls only: documented infrastructure findings (safbox-*) can
    # sit in the same lists and are described in the threshold's header.
    return {sev: [c for c in (t["failed"].get(sev) or {}).get("controls") or [] if c.startswith("SV-")]
            for sev in SEVERITIES}


def pointer(cid):
    if cid in {k["vuln_id"] for k in known}:
        return "known defect (`known-defects.yml`)"
    if cid in {n["vuln_id"] for n in not_applied}:
        return "task failed (`not_applied.yml`)"
    return f"not yet triaged ({TRIAGE_CARD})"

def cell(text):
    return " ".join(str(text).split()).replace("|", "\\|")

def switch(stig_id):
    return "rhel10stig_" + stig_id.removeprefix("RHEL-10-")

lines = [
    "# SAFBox STIG deviations",
    "",
    "<!-- Generated by scripts/deviations-doc.sh from",
    "     ansible/roles/hardening/vars/{deviations,not_applied}.yml,",
    "     verify/safbox-rhel10-stig-overlay/{known-defects,baseline-titles}.yml",
    "     and verify/thresholds/{release,build}.yml.",
    "     Do not edit; change those files and regenerate. -->",
    "",
    "SAFBox applies the DISA RHEL 10 STIG with the Ansible Lockdown",
    "RHEL10-STIG role and validates it with the MITRE RHEL 10 STIG baseline",
    "through the SAFBox overlay (`verify/safbox-rhel10-stig-overlay`). The",
    "pins are in `ansible/group_vars/all/main.yml` and the overlay's",
    "`inspec.yml`. The aim is a usable, documented security state, not a",
    "clean report: every requirement SAFBox does not meet is either a",
    "deviation listed here or a failing finding in the scan.",
    "",
    "## Deviations",
    "",
    "Requirements SAFBox deliberately does not apply. The hardening role",
    "switches each one off with the Lockdown role's per-rule variable, and the",
    "overlay marks it Not Applicable (impact 0.0) with the justification",
    "below. Reason codes: `usability` (relaxed for the non-expert audience),",
    "`content-defect` (an upstream role or profile bug, retired when the fix",
    "is pinned) and `deploy-time` (only the deploying environment can satisfy",
    "it).",
    "",
    "| STIG ID | Rule | Requirement | Reason | Lockdown variable | Justification |",
    "|---|---|---|---|---|---|",
]
for d in deviations:
    reason = d["reason"]
    if d.get("issue"):
        reason += f" ([issue]({d['issue']}))"
    if d.get("site_setting"):
        reason += f", until a site sets `safbox_{d['site_setting']}`"
    lines.append(f"| {d['stig_id']} | {d['vuln_id']} | {cell(d['title'])} | {reason} | "
                 f"`{switch(d['stig_id'])}` | {cell(d['justification'])} |")
lines += [
    "",
    "## Rules not applied because their Lockdown task fails",
    "",
    "Rules switched off only so that the hardening run completes, because the",
    "Lockdown task errors on SAFBox. They are not deviations: the overlay does",
    "not touch them, so the baseline control still runs and its result,",
    "whatever it is, is locked in `verify/thresholds/` until the task is",
    "fixed and the entry removed. The scan column says what that result is.",
    "",
]
if not_applied:
    lines += ["| STIG ID | Rule | Lockdown variable | Failure seen | Scan result |", "|---|---|---|---|---|"]
    for n in not_applied:
        lines.append(f"| {n['stig_id']} | {n['vuln_id']} | `{switch(n['stig_id'])}` | {cell(n['failure'])} | "
                     f"{cell(n['scan'])} |")
else:
    lines.append("None.")
lines += [
    "",
    "## Known baseline defects (not deviations)",
    "",
    "Controls of the pinned MITRE baseline that report a wrong or",
    "unevaluated result on SAFBox. They are not deviations: the control stays",
    "in force and its result is locked as it is. Recorded in",
    "`verify/safbox-rhel10-stig-overlay/known-defects.yml`.",
    "",
]
if known:
    lines += ["| Rule | Scan result | Defect | Upstream issue |", "|---|---|---|---|"]
    for k in known:
        issue = f"[issue]({k['issue']})" if k.get("issue") else "not yet filed"
        lines.append(f"| {k['vuln_id']} | {k['result']} | {cell(k['defect'])} | {issue} |")
else:
    lines.append("None.")
lines += [
    "",
    "## Remaining failures",
    "",
    "Every other requirement that fails is a known weakness and stays visible.",
    "This is every STIG control that fails on a deployed clone, per severity,",
    "as locked in `verify/thresholds/release.yml` (the gate fails on any",
    "change). Titles are the baseline's",
    "(`verify/safbox-rhel10-stig-overlay/baseline-titles.yml`).",
    "",
]
release, build = failing("release"), failing("build")
for sev in SEVERITIES:
    lines += [f"### {sev.capitalize()} ({len(release[sev])})", ""]
    if release[sev]:
        lines += ["| Rule | Requirement | Status |", "|---|---|---|"]
        for cid in release[sev]:
            lines.append(f"| {cid} | {cell(titles.get(cid, {}).get('title', '(title not in the baseline)'))} | "
                         f"{pointer(cid)} |")
    else:
        lines.append("None.")
    lines.append("")
build_only = [(sev, cid) for sev in SEVERITIES for cid in build[sev] if cid not in release[sev]]
lines += [
    "### The build context",
    "",
    "The build-time gate scans the build VM before it is ever rebooted after",
    "hardening, so settings that take effect at boot are not yet in force and",
    "`verify/thresholds/build.yml` locks more failures: "
    + ", ".join(f"{sev} {len(build[sev])}" for sev in SEVERITIES) + ". Failing",
    "only there:",
    "",
]
if build_only:
    lines += ["| Rule | Severity | Requirement |", "|---|---|---|"]
    for sev, cid in build_only:
        lines.append(f"| {cid} | {sev} | {cell(titles.get(cid, {}).get('title', '(title not in the baseline)'))} |")
else:
    lines.append("None.")
lines += [
    "",
    "## Settings a site will want to know about",
    "",
    "- **Login banner.** SAFBox ships a short placeholder banner, not the DoD",
    "  notice (`safbox_logon_banner` in `ansible/group_vars/all/main.yml`).",
    "  Set your own in `ansible/local.yml`, and the same text for the",
    "  overlay's `banner_message_text_cli`, `banner_message_text_ral` and",
    "  `banner_message_text_gui` inputs in your site inputs file.",
    "- **Remote logging is off by default.** SAFBox forwards no logs, and",
    "  SV-280985 is a deploy-time deviation, until a site names its log",
    "  server: set `safbox_remote_log_server` (and `safbox_remote_log_port`,",
    "  `safbox_remote_log_protocol`, tcp or udp) in `ansible/local.yml`, and",
    "  the overlay input `remote_log_server` to the same server in your site",
    "  inputs file. The hardening then writes",
    "  `/etc/rsyslog.d/99-forwarding.conf` for that server and SV-280985 is",
    "  evaluated. SV-280987 and SV-280988 (TLS authentication and encryption",
    "  of the forwarded records) remain deviations until the site also",
    "  provides certificates and switches those rules on.",
    "- **USB devices are blocked by default.** The hardening enables USBGuard",
    "  with no rules and its implicit policy set to block, so no USB device is",
    "  authorized. To allow one, list it with `usbguard list-devices` and",
    "  allow it permanently with `usbguard allow-device -p <id>`, or write a",
    "  rule set with `usbguard generate-policy` into",
    "  `/etc/usbguard/rules.conf`.",
    "",
    "## Changing the posture for your site",
    "",
    "Each control is a knob. To apply a deviated requirement, remove its entry",
    "from `deviations.yml` and its override from",
    "`verify/safbox-rhel10-stig-overlay/controls/overlay.rb` together",
    "(`scripts/deviations-check.sh` fails if they disagree), then regenerate",
    "this guide. To switch a further rule off, or change a value the Lockdown",
    "role applies, set its `rhel10stig_*` variable in `ansible/local.yml`. A",
    "site that changes what is applied supplies its own threshold",
    "(`docs/rebuild.md`, Site inputs and thresholds).",
    "",
]
out.write_text("\n".join(lines))
print(f"deviations-doc.sh: wrote {out}")
PY
