#!/usr/bin/env bash
# 40-proxy.sh: first-boot hook of the proxy role. Generates the TLS proxy's
# self-signed certificate (ADR-0001 §Decision: first boot mints a
# self-signed certificate), never at build:
#   /etc/safbox/tls/safbox.key  RSA 3072, root only (0600)
#   /etc/safbox/tls/safbox.crt  self-signed, SHA-256, valid SAFBOX_TLS_DAYS
#                               days (default 365), naming the host name,
#                               localhost and every address the host has now
# Upstream Heimdall's setup-docker-env.sh makes a 7-day RSA 4096 certificate
# for testing; an appliance needs one that outlasts a working week. Keys and
# hashes are FIPS-approved and generated by the host's OpenSSL, in FIPS mode.
#
# Existing files are kept: to use your own certificate, replace both files;
# to regenerate (after the host's name or address changes), delete both and
# run this hook as root, then restart safbox-proxy.service.
set -euo pipefail
umask 077

SAFBOX_ETC_DIR=${SAFBOX_ETC_DIR:-/etc/safbox}
days=${SAFBOX_TLS_DAYS:-365}
tls_dir="${SAFBOX_ETC_DIR}/tls"
key="${tls_dir}/safbox.key"
cert="${tls_dir}/safbox.crt"

install -d -m 0700 -o root -g root "$tls_dir"
if [[ -e "$key" && -e "$cert" ]]; then
  echo "40-proxy.sh: keeping the existing certificate ${cert}"
  exit 0
fi
if [[ -e "$key" || -e "$cert" ]]; then
  echo "40-proxy.sh: only one of ${key} and ${cert} exists; supply both or remove both" >&2
  exit 1
fi

fqdn=$(hostname -f 2>/dev/null || hostname)
short=$(hostname -s 2>/dev/null || hostname)
san="DNS:${fqdn}"
if [[ "$short" != "$fqdn" ]]; then san+=",DNS:${short}"; fi
san+=",DNS:localhost,IP:127.0.0.1"
for address in $(hostname -I 2>/dev/null); do
  san+=",IP:${address}"
done

openssl req -x509 -newkey rsa:3072 -sha256 -days "$days" -nodes \
  -subj "/CN=${fqdn}" \
  -addext "subjectAltName=${san}" \
  -addext "keyUsage=critical,digitalSignature,keyEncipherment" \
  -addext "extendedKeyUsage=serverAuth" \
  -keyout "${key}.new" -out "${cert}.new" 2>/dev/null
chown root:root "${key}.new" "${cert}.new"
chmod 0600 "${key}.new"
chmod 0644 "${cert}.new"
mv "${key}.new" "$key"
mv "${cert}.new" "$cert"
echo "40-proxy.sh: generated ${cert} for ${san}"
